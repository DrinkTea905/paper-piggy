# -*- coding: utf-8 -*-
"""⛔ 废稿 · 请勿执行 · 永不发布（用户 2026-08-14 判定作废）

本脚本随《论文初稿（少年司法·三大刊版）》一并作废。
**决定性证据就出自它自己**：它对 v4 试跑的丙稿判定几乎全绿（统计型 5 项、体例型 6 项、
下限 2 项全过，讲解腔 0），而用户判定该稿「很烂」——**指标全绿 ≠ 文章可用**。
保留只作失败样本与工具参考；不得作为验收依据。
复盘见 docs/设计/少年司法初稿v5/v4失败复盘.md。

★ 若 v5 复用本脚本，先修这三个已知缺陷（C 稿实跑暴露，未修）：
  1. .md 分支的脚注剥离失效——先删 [^n] 导致第二条正则再也匹配不到脚注定义行，
     结果把脚注全算进正文（同一稿 md 报 35,733 汉字、docx 报 27,170，冒号密度 43→96）。
     只跑 .docx 才与 106 篇真刊的基准口径一致。
  2. 「正文具名指称他人研究」正则过宽，会把「本文主张」「问题的提出」计入
     （C 稿报 90 处，逐条核后真正的人名＋判断动词只有 1 处）。
  3. 「凑三」正则会命中法条的「第三项」「第三款」。

────────────────────────────────────────
论文初稿（少年司法·三大刊版）· 行文体检〔废稿〕

用法：
    python check_style.py 稿件.docx
    python check_style.py 稿件.md
    python check_style.py 稿件.docx --json

支持 .docx / .md / .txt。docx 只读正文段落（脚注不计入，与基准口径一致）。

基准与阈值一律按【汉字数】，且**在 106 篇三大刊单篇上逐篇校准**（不是在合计语料上）。
逐篇误伤率：§5.1 五项 ≤1%，§5.4 两项 ≤10%。
详见 docs/设计/少年司法初稿工作流v4-三大刊改造方案.md 与同目录工作流文件 §5。

**这是体检，不是写作指令**：写完再跑，超标处逐个重写；不要在起草时凑数。
**下限项（§5.4）不阻断交付**——达不到是材料问题，回去补材料，不是把词加进去。
"""
import json
import os
import re
import statistics as st
import sys

sys.stdout.reconfigure(encoding="utf-8")


# ---------- 读稿 ----------

def load(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == ".docx":
        try:
            import docx  # python-docx
        except ImportError:
            sys.exit("需要 python-docx 才能读 .docx：pip install python-docx\n"
                     "或先把正文另存为 .md / .txt 再跑。")
        d = docx.Document(path)
        return "\n".join(p.text for p in d.paragraphs)
    t = open(path, encoding="utf-8", errors="ignore").read()
    if ext in (".md", ".markdown"):
        t = re.sub(r"\[\^[^\]]+\]", "", t)
        t = re.sub(r"(?m)^\[\^[^\]]+\]:.*$", "", t)
        t = re.sub(r"(?m)^\s*[>|].*$", "", t)
        t = re.sub(r"[*`_]", "", t)
    return t


def strip_abstract(t):
    """去掉题名、作者、摘要、关键词，返回正文。用于「开篇三件套」这类只看正文首段的检查。"""
    m = re.search(r"(【关键词】|关键词[:：])[^\n]*\n", t)
    if m:
        return t[m.end():]
    m = re.search(r"^\s*(一|1)[、.．]", t, re.M)
    return t[m.start():] if m else t


# ---------- 指标 ----------
# §5.1 统计型：语料证明能区分（AI 三份稿全部落在 106 篇真刊分布之外）
#      (名称, 正则, 真刊中位, 真刊p95, 阈值, 单位)  单位 "cnt"=处数 / "rate"=每万汉字
STAT = [
    ("有论述（作主语）",   r"(?<![所具含占})])有论述|另有论述|已有论述", 0.00, 0.00, 0,    "cnt"),
    ("本节／本章（自指）", r"本[节章]",                              0.00, 0.00, 1,    "cnt"),
    ("「这一＋抽象名词」", r"这一[一-鿿]",                            7.11, 19.44, 21.4, "rate"),
    ("凑三（三点/三项…）", r"三[点项重组]|三个(层次|方面|坐标)|理由有三",  0.49, 2.54, 2.8,  "rate"),
    ("本文",             r"本文",                                  1.82, 8.06, 8.9,  "rate"),
]

# §5.2 体例型：不靠统计，靠期刊体例与常识
STYLE = [
    ("「」引号（大陆材料应用“”）", r"「"),
    ("工作流术语泄漏（落位/闸门/选边/两栏）", r"落位|闸门|选边|交付名词|骨架卡|两栏"),
    ("汉字与阿拉伯数字间的半角空格", r"(?<=[一-鿿]) (?=\d)|(?<=\d) (?=[一-鿿])"),
    ("如实交代／如实指出", r"如实(交代|指出|说明)"),
    ("「据此，第X条可拟为」同句式", r"据此[，,][^。]{0,12}条(可|可以)(拟为|表述为)"),
]

# §5.4 下限：仅两项通过逐篇回测
REC = [
    ("例如／比如／又如／再如", r"例如|比如|又如|再如|譬如", 5.14, 1.07),
    ("但是／然而／虽然／尽管／而且", r"但是|然而|虽然|尽管|而且", 14.16, 5.64),
]

# §5.3 只报数（真刊单篇方差极大，设阈值必然误伤）
INFO = [
    ("不是A而是B／而不是",   r"不是[^。]{1,20}而是|而不是|不在于[^。]{1,20}而在于", 1.79, 9.22),
    ("破折号",             r"——|--",                              1.23, 8.72),
    ("分号",               r"[；;]",                               15.58, 33.84),
    ("冒号",               r"[：:]",                               19.45, 46.62),
    ("应当／不得",          r"应当|不得",                            9.55, 31.54),
    ("元评论总起",          r"[值需][得要][^。]{0,4}[说指注][明出意]",    0.49, 3.20),
    ("平判断词",            r"难以成立|不能成立|难以自圆|并无规范依据",     0.00, 0.98),
    ("归结起来／如此看来组",  r"归结起来|如此看来|这足以说明|严格说来",       0.00, 0.51),
    ("讲解腔",             r"先说|再说|接下来|第[一二三四]组|[须还]先?说明|有它的道理|问题就出在|最要紧|的好处|无非是", 0.00, 1.28),
    ("问号",               r"[？?]",                               2.52, 20.73),
    ("笔者",               r"笔者",                                1.42, 8.22),
    ("让步词",             r"的确|确实|不可否认|应当承认",              2.19, 6.14),
    ("实践中／调研中",       r"实践中|调研中|实务上|实务中",              3.01, 8.15),
]

# §9 引注三条（用户长期规则，命中须为 0）
CITE = [
    ("前引／同前注／同上注／Ibid", r"前引|同前注|同上注|Ibid"),
    ("正文具名指称他人研究", r"[一-鿿]{2,4}(教授|老师|学者)?(认为|指出|主张|提出|强调)"),
]

# §5.6 口语按特征查
ORAL = [
    ("讲解腔：先说／再说／接下来", r"先说|再说|接下来|下面先|我们先"),
    ("讲解腔：第一组／第二组",     r"第[一二三四]组"),
    ("讲解腔：须先说明",          r"[须还]先?说明|需要先说明"),
    ("有它的道理／问题就出在这里",  r"有它的道理|有其道理|问题就出在"),
    ("最要紧／的好处／无非是",     r"最要紧|的好处|无非是|不复杂"),
    ("口语疑问式（有没有/能不能）", r"有没有|够不够|存不存在|是不是|能不能"),
    ("动补否定（堵不上/靠不住）",  r"[堵配靠说用抓管顶撑扛]得?不[上住清起来了通过]"),
    ("「家」作机关量词",          r"[一两三四五几]家(机关|单位|法院|检察院|部门)"),
    ("英文直译腔（问题是真实的）",  r"问题是真实的|是真实的[。，]"),
]

ANON = ["有学者认为", "有学者指出", "有的学者", "论者指出", "论者认为", "一种有影响的主张",
        "另一种意见", "通说认为", "学界通行", "持相反立场", "代表性观点", "较有代表性",
        "有研究表明", "有研究显示", "有实证研究"]


def han(t):
    return len(re.findall(r"[一-鿿]", t))


def run(path, as_json=False):
    text = load(path)
    n = han(text)
    if n < 500:
        sys.exit("正文汉字不足 500，读取可能失败：%s" % path)
    per = lambda p: len(re.findall(p, text, re.M)) / n * 10000
    cnt = lambda p: len(re.findall(p, text, re.M))

    res = {"file": path, "汉字数": n, "统计型": [], "体例型": [], "下限": [],
           "只报数": [], "引注": [], "口语": [], "匿名指称": {}, "句段": {}}

    for name, pat, med, p95, thr, unit in STAT:
        v = cnt(pat) if unit == "cnt" else round(per(pat), 2)
        res["统计型"].append({"项": name, "值": v, "单位": "处" if unit == "cnt" else "/万字",
                              "阈值": thr, "真刊中位": med, "真刊p95": p95,
                              "判定": "OK" if v <= thr else "超标"})
    for name, pat in STYLE:
        c = cnt(pat)
        res["体例型"].append({"项": name, "命中": c, "判定": "OK" if c == 0 else "超标"})

    body = strip_abstract(text)[:400]
    c = len(re.findall(r"随着|日益|背景下", body))
    res["体例型"].append({"项": "开篇「随着/日益/背景下」三件套（只查正文首段）",
                          "命中": c, "判定": "OK" if c == 0 else "超标"})

    for name, pat, med, thr in REC:
        v = per(pat)
        res["下限"].append({"项": name, "每万字": round(v, 2), "下限": thr, "真刊中位": med,
                            "判定": "OK" if v >= thr else "不足"})
    for name, pat, med, p95 in INFO:
        res["只报数"].append({"项": name, "每万字": round(per(pat), 2),
                              "真刊中位": med, "真刊p95": p95})
    for name, pat in CITE:
        res["引注"].append({"项": name, "命中": cnt(pat)})
    for name, pat in ORAL:
        c = cnt(pat)
        if c:
            res["口语"].append({"项": name, "命中": c})

    used = {a: cnt(a) for a in ANON if cnt(a)}
    over = {k: v for k, v in used.items() if v > 3}
    res["匿名指称"] = {"种类数": len(used), "明细": used, "连用超3次": over,
                       "判定": "OK" if not over else "有措辞连用超 3 次"}

    ss = [s for s in re.findall(r"[^。？！\n]+[。？！]", text) if len(s) >= 6]
    if ss:
        L = [len(s) for s in ss]
        res["句段"] = {"句数": len(ss), "均句长": round(st.mean(L), 1), "中位": st.median(L),
                       "短句占比%": round(100 * sum(1 for x in L if x < 20) / len(L), 1)}

    if as_json:
        print(json.dumps(res, ensure_ascii=False, indent=1))
        return res

    print("=" * 80)
    print("行文体检 · %s（正文 %d 汉字）" % (os.path.basename(path), n))
    print("=" * 80)
    if n > 60000:
        print("⚠ 超过 6 万汉字，像是语料而非单篇稿件。处数类判定只对单篇有意义。")

    print("\n【§5.1 统计型禁区／上限】进硬失败。106 篇真刊逐篇校准，误伤率 ≤1%")
    for r in res["统计型"]:
        print("  %-22s %8s%-5s 阈值 %-6s (真刊 中位%.2f p95%.2f)  %s"
              % (r["项"], r["值"], r["单位"], r["阈值"], r["真刊中位"], r["真刊p95"],
                 "✓" if r["判定"] == "OK" else "✗ 超标"))

    print("\n【§5.2 体例型禁区】进硬失败。不靠统计，靠期刊体例")
    for r in res["体例型"]:
        print("  %-46s 命中 %4d  %s" % (r["项"][:46], r["命中"],
                                        "✓" if r["判定"] == "OK" else "✗"))

    print("\n【§5.4 下限】不阻断交付；不足＝材料问题，回去补材料")
    for r in res["下限"]:
        print("  %-22s %7.2f/万字  下限 %-6s (真刊中位 %.2f)  %s"
              % (r["项"], r["每万字"], r["下限"], r["真刊中位"],
                 "✓" if r["判定"] == "OK" else "△ 不足"))

    print("\n【§5.3 只报数】真刊单篇方差极大，不设阈值——数字给人看，人来判断")
    print("  %-22s %10s %10s %10s" % ("项", "本稿/万字", "真刊中位", "真刊p95"))
    for r in res["只报数"]:
        flag = ""
        if r["每万字"] > r["真刊p95"]:
            flag = "  ← 高于真刊 p95"
        elif r["每万字"] < r["真刊中位"] / 3:
            flag = "  ← 不足真刊中位 1/3"
        print("  %-22s %10.2f %10.2f %10.2f%s" % (r["项"], r["每万字"], r["真刊中位"], r["真刊p95"], flag))

    print("\n【§9 引注三条】命中须为 0")
    for r in res["引注"]:
        print("  %-30s 命中 %4d  %s" % (r["项"], r["命中"], "✓" if r["命中"] == 0 else "✗"))

    a = res["匿名指称"]
    print("\n【§5.5 匿名指称】不设种类下限；同一措辞连用 ≤3 次")
    print("  种类数 %d  %s" % (a["种类数"], "✓" if a["判定"] == "OK" else "✗ " + a["判定"]))
    for k, v in sorted(a["明细"].items(), key=lambda kv: -kv[1]):
        print("    %-14s %d 次%s" % (k, v, "   ✗ 连用超 3 次" if v > 3 else ""))

    if res["口语"]:
        print("\n【§5.6 口语·按特征查】三大刊密度均 <0.1/万字，逐处重写")
        for r in res["口语"]:
            print("  %-30s %d 处" % (r["项"], r["命中"]))
    else:
        print("\n【§5.6 口语】未检出 ✓")

    s = res["句段"]
    print("\n【句段形态】句数 %d  均句长 %.1f  中位 %d  短句(<20字)占比 %.1f%%（三大刊 5.8%%，不设阈值）"
          % (s["句数"], s["均句长"], s["中位"], s["短句占比%"]))

    bad = sum(1 for r in res["统计型"] if r["判定"] != "OK") + \
          sum(1 for r in res["体例型"] if r["判定"] != "OK") + \
          sum(1 for r in res["引注"] if r["命中"] != 0)
    low = sum(1 for r in res["下限"] if r["判定"] != "OK")
    print("\n" + "-" * 80)
    print("硬失败项超标 %d ｜ 下限不足 %d（不阻断，回去补材料）" % (bad, low))
    print("结构指标不在本表——结构只诊断、不达标要求，见工作流 §6。")
    return res


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        sys.exit(__doc__)
    run(args[0], as_json="--json" in sys.argv)
