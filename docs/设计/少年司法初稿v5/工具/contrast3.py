"""对照分析 v3：定点词表 + 句法/标点/篇章指标。频率一律折算为「每万字」。"""
import os, re, sys, statistics as st
sys.stdout.reconfigure(encoding='utf-8')

HERE = os.path.dirname(os.path.abspath(__file__))
C = os.path.join(HERE, "corpus")
load = lambda n: open(os.path.join(C, n), encoding="utf-8").read()
A, R1, R2 = load("A_AI稿.txt"), load("R1b_三大刊加中外法学.txt"), load("R2_少年司法真人.txt")
CORP = [("AI稿", A), ("三大刊", R1), ("少司真人", R2)]

def rate(t, pat):
    return len(re.findall(pat, t)) / len(t) * 10000

def table(title, items):
    print("=" * 92)
    print(title)
    print("=" * 92)
    print("%-24s %9s %9s %9s %8s" % ("项目", "AI/万字", "三大刊", "真人", "AI倍数"))
    for name, pat in items:
        vals = [rate(t, pat) for _, t in CORP]
        base = max(vals[1], vals[2], 0.01)
        flag = ""
        if vals[0] >= base * 2.5 and vals[0] >= 0.5:
            flag = "  ← AI 过度"
        elif vals[0] * 2.5 <= min(vals[1], vals[2]) and max(vals[1], vals[2]) >= 1.0:
            flag = "  ← AI 缺失"
        print("%-24s %9.2f %9.2f %9.2f %8.1f%s" % (name, vals[0], vals[1], vals[2], vals[0] / base, flag))
    print()

