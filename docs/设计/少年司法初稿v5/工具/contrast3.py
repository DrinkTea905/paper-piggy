SENT = re.compile(r"[^。？！]+[。？！]")
for name, t in CORP:
    ss = [s for s in SENT.findall(t) if len(s) >= 6]
    lens = [len(s) for s in ss]
    commas = [s.count("，") for s in ss]
    paras = [p for p in t.split("\n") if len(p) > 50]
    print("%-8s 句数%6d | 句长 均%5.1f 中位%4d p90%4d 最长%4d | 每句逗号 均%4.2f | 长句(>80字)占比%5.1f%% | 短句(<20字)占比%5.1f%%"
          % (name, len(ss), st.mean(lens), st.median(lens), sorted(lens)[int(len(lens) * .9)], max(lens),
             st.mean(commas), 100 * sum(1 for x in lens if x > 80) / len(lens),
             100 * sum(1 for x in lens if x < 20) / len(lens)))
