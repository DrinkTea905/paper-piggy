w("**第 2 步是本轮新增的装置，也是 v4 最缺的东西。** v4 只有第 1 步，于是丙稿把五项压绿之后，")
w("AI 味迁移到「所设的」（真刊零出现、丙稿 6.15）这类没被测的表达上，指标却宣告通过。")
