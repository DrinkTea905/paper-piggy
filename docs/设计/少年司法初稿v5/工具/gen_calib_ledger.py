sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
HERE = os.path.dirname(os.path.abspath(__file__))
rows = json.load(open(os.path.join(HERE, "calib_v5.json"), encoding="utf-8"))
NAMES = ["丙稿(v4)", "甲稿(无手册)", "乙稿(v3手册)", "平行稿(用户大纲)"]

out = []
w = out.append
w("# 阶段 4 · 阈值校准")
w("")
w("> 产出日期：2026-08-14。工具：`工具/calibrate_v5.py`（逐篇，不用合计口径）。")
w("> 两条硬要求（用户定）：① 阈值必须在**单篇**真刊上校准并报误伤率，>10% 即阈值错；")
w("> ② 同时报「AI 四稿是否全部落在真刊分布之外」——**只有两头都满足才算能区分**。")
w("")
w("## 一、阈值策略与误伤率")
w("")
w("阈值一律取**真刊单篇最大值**，因此真刊误伤率恒为 **0.0%**，远优于 >10% 的红线。")
w("")
w("作为对照：若照 v4 的做法把阈值取在 p95，每项约误伤 5%% 的真刊，"
  "**%d 项叠加后一篇真刊能全过的概率只有 %.0f%%**——这正是 v4 初版「106 篇真刊只有 1 篇全过」的算法来源。"
  % (len(rows), 100 * (0.95 ** len(rows))))
w("")
w("判定分两类，**不可混为一谈**（本轮首版脚本混了，当场导致误判，已修）：")
w("")
w("| 类 | 判据 | 含义 |")
w("|---|---|---|")
w("| **零阈值禁令** | 106 篇三大刊 ＋ 143 篇少年司法真人**双双零出现** | 它是体例外的东西，与「AI 稿是否都犯」无关 |")
w("| **上限** | 真刊有分布，且 AI **四稿全部**超过真刊单篇最大值 | 这才叫测到了 AI 与真人的分界 |")
w("| 只报数 | 只有部分 AI 稿超 | 测的是那一稿的习惯，不是 AI 与真人的分界 |")
w("| 撤销 | 无一稿超过真刊上限 | 别再提 |")
w("")
w("> **为什么零阈值禁令不要求「AI 稿全犯」**：丙稿的「有论述」是 0 处，正是因为 v4 已经禁了它、"
  "而且禁令**奏效**了。把这算作「指标失效」是把因果读反。")
w("")
w("## 二、逐项结果")
w("")
w("| 来源 | 项 | 真刊中位 | p95 | **真刊单篇max** | 零出现篇%% | 少司真人max | %s | 处置 |"
  % " | ".join(NAMES))
w("|---|---|---:|---:|---:|---:|---:|%s|---|" % ("---:|" * 4))
order = {"★零": 0, "★上": 1, "只报": 2, "禁令": 3, "撤销": 4}
for r in sorted(rows, key=lambda x: order.get(x["verdict"][:2], 9)):
    w("| %s | %s | %.2f | %.2f | **%.2f** | %.0f%% | %.2f | %s | %s |"
      % (r["src"], r["name"], r["median"], r["p95"], r["max"], r["zero_pct"], r["l2_max"],
         " | ".join("%.2f" % x for x in r["ai"]), r["verdict"]))
w("")
n0 = sum(1 for r in rows if "零阈值" in r["verdict"])
n1 = sum(1 for r in rows if r["verdict"].startswith("★上限"))
n2 = sum(1 for r in rows if "只报数" in r["verdict"])
n3 = sum(1 for r in rows if "撤销" in r["verdict"])
w("**%d 项候选 → 零阈值禁令 %d 项、上限 %d 项、只报数 %d 项、撤销 %d 项。**" % (len(rows), n0, n1, n2, n3))
w("")
w("## 三、★ 本阶段订正了阶段 0 的三处判断（含我自己的一次「凭少数篇目定结论」）")
w("")
w("### 1. 破折号说理：原判「可直接设硬上限」→ **撤销**")
w("")
w("阶段 0 的 S14 我写的是「破折号一项可直接设硬上限（真刊正文近乎为 0，误伤率极低）」。**这是错的。**")
w("")
w("| | 真刊中位 | 真刊 p95 | **真刊单篇 max** | 丙稿 | 乙稿 |")
w("|---|---:|---:|---:|---:|---:|")
w("| 破折号 | 1.23 | 8.72 | **20.05** | 9.41 | 19.96 |")
w("")
w("真刊单篇最高用到 20.05/万字，**四稿没有一稿超过它**。原判断的来源是丙稿诊断子代理的一句观察——")
w("「董坤＋汪海燕两篇合计 24 页，正文说理处破折号为 0」。那是 **n=2**，我据此推广到 106 篇。")
w("")
w("> **这是本轮「凭少数篇目定结论」的第五次发作，而且是我自己犯的。**")
w("> 前四次记在 v4 §5.4 被否掉的四条候选下限里，第五次是 v4 §3.3 的「回到原点」（n=1）。")
w("> 教训不变：**任何从精读篇目提炼的观察，投放前必须在 106 篇上逐篇回测。**")
w("")
w("### 2. 「恰恰」：原判「超过全部 106 篇」→ **降为只报数**")
w("")
w("丙稿 5.79 确实超过真刊单篇最大值 3.81——但**甲稿只有 2.99，没超**。")
w("四稿没有全部落在真刊分布之外，所以它测的是**丙稿这一稿的习惯**，不是 AI 与真人的分界。")
w("阶段 0 的表述「超过全部 106 篇真刊」就丙稿而言属实，但**不足以让它进禁区表**。")
w("")
w("### 3. 「作业类元叙述」「元话语连接件」→ **双双撤销**")
w("")
w("| 项 | 真刊单篇 max | 四稿最高 |")
w("|---|---:|---:|")
w("| 作业类元叙述（未能取得／经查均无／这并非检索） | 0.61 | 0.37 |")
w("| 元话语连接件（需要说明的是／应当指出的是） | 4.27 | 4.11 |")
w("")
w("**无一稿超过真刊上限。** 这一条订正很重要，因为盲读者曾说元叙述是「本稿与真刊之间唯一稳定的判据」——")
w("现在数据说明：**元叙述的病不在频次，在位置与功能**。真刊也写自述，但那些自述承载的是样本口径、")
w("分母、时间窗、可信范围（见 R9 的两个反例）；AI 稿的自述承载的是「我查过了」。")
w("**频次拦不住，也不该拦——交给规则 R9 逐句判断。**")
w("")
w("## 四、进禁区表的 7 项（体例检查用，不占规则名额）")
w("")
w("### 零阈值禁令 6 项（249 篇真人文献零出现）")
w("")
for r in rows:
    if "零阈值" in r["verdict"]:
        w("- **%s**　`%s`" % (r["name"], r["pattern"]))
w("")
w("### 上限 1 项")
w("")
for r in rows:
    if r["verdict"].startswith("★上限"):
        w("- **%s** ≤ %.2f/万字　`%s`　（真刊中位 %.2f，四稿 %s）"
          % (r["name"], r["max"], r["pattern"], r["median"], "／".join("%.2f" % x for x in r["ai"])))
w("")
w("## 五、只报数 5 项（给人看，不阻断交付）")
w("")
for r in rows:
    if "只报数" in r["verdict"]:
        w("- %s：真刊中位 %.2f、单篇 max %.2f｜四稿 %s　—— %s"
          % (r["name"], r["median"], r["max"], "／".join("%.2f" % x for x in r["ai"]), r["verdict"]))
w("")
w("## 六、这张表会过期——所以配了表外扫描")
w("")
w("阶段 0 的方法论结论是：**任何固定且公开的可数指标集，都会被优化到全绿，"
  "同时把 AI 味挤到集合之外。** 本表也不例外——它是 2026-08-14 这一刻的表，不是永久的表。")
w("")
w("因此 v5 的体检流程固定为两步，**缺一不可**：")
w("")
w("1. 跑本表（`calibrate_v5.py`）——查已知的 7 项；")
w("2. 跑表外扫描（`outlier_ngram.py`）——拿新稿与 106 篇三大刊＋143 篇少年司法真人**逐篇**比，"
  "自动找出「本稿超过全部真刊」的表达，**人工判读后回写本表**。")
