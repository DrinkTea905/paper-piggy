def _current_sidecar(key, path, current_text, mask=None):
    """找出内容等于当前出厂版的待合并文件；用户改过的旧件不会被误认。"""
    wanted = _template_hash(key, current_text, mask)
    for p in _pending_candidates(key, path):
        try:
            if p.exists() and _template_hash(key, p.read_text(encoding="utf-8"), mask) == wanted:
                return p
        except Exception:
            continue
    return None


def upgrade_status(include_ignored=False):
    """返回用户可见的出厂模板升级状态；只把可合并的指引/工作流列为待办。"""
    ensure_scaffold()
    state = _load_update_state()
    items = []
    for key, path, text, mask, seed in _template_specs():
        if seed:
            continue
        cur_h = _template_hash(key, text, mask)
        try:
            main_h = _template_hash(key, path.read_text(encoding="utf-8"), mask)
        except Exception:
            main_h = ""
        if main_h == cur_h:
            status, sidecar = "current", None
        else:
            sidecar = _current_sidecar(key, path, text, mask)
            status = "pending" if sidecar else "customized"
            if state.get(key) == cur_h:
                status = "ignored"
        if status == "current" or (status == "ignored" and not include_ignored):
            continue
        label = path.name
        if key.startswith("rely/技能/参考手册/"):
            label = "伴随手册 · " + path.stem
        elif key.startswith("rely/技能/"):
            label = "工作流 · " + path.stem
        elif key == "rely/README.md":
            label = "专属资料库说明"
        elif key == "output/README.md":
            label = "交付物说明"
        items.append({
            "kind": "agent", "key": key, "label": label, "status": status,
            "main_path": str(path), "new_path": str(sidecar or ""),
            "current_hash": cur_h, "main_hash": main_h,
        })
    return {"pending_count": sum(x["status"] == "pending" for x in items), "items": items}


