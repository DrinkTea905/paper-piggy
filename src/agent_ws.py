def ensure_scaffold():
    """幂等创建两个文件夹的骨架 + README + 记忆/模板/工作流。可反复调用（server/mcp 每次启动、多处端点都调）；
       异常吞掉不阻断主流程。出厂模板走 _ensure_template：没改过的**跟着版本升级**、改过的原样保留（见上面注释）。
       返回 {名单键: 动作} 供测试/排查；正常调用方忽略即可。"""
    acts = {}
    try:
        for d in (output_dir(), output_dir() / "定时任务", rely_dir(),
                  memory_dir(), topics_dir(),
                  skills_dir(), handbooks_dir(), formats_dir(), templates_dir(), tasks_dir(),
                  maintenance_dir(), pending_dir(), history_dir()):
            try:
                d.mkdir(parents=True, exist_ok=True)
            except Exception:
                pass
        # 顺序要紧：先把旧版散落的状态、旁本和恢复件集中收纳，再迁移旧工作流，最后铺新模板。
        acts["migration/升级与备份布局"] = _migrate_legacy_maintenance_layout()
        _migrate_legacy_workflow()
        acts["migration/写论文与综述.md"] = _migrate_combined_paper_workflow()
        _remove_obsolete_catalog_check_task()
        for key, path, text, mask, seed in _template_specs():
            acts[key] = _ensure_template(
                path, text, _factory_hashes_for(key), mask, seed, key=key)
    except Exception:
        pass
    return acts


